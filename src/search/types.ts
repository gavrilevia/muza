/**
 * Типы поиска по слову.
 *
 * Индекс ищет по трём полям идеи: заголовку, телу и тексту, извлечённому
 * из материалов (`extracted_text`). Всё остальное — направление, статус,
 * даты — это фильтры, а не поиск, и в индексе им делать нечего.
 *
 * Оговорка про смысл: здесь именно поиск по слову, а не по смыслу.
 * Ни сети, ни ИИ в этом модуле нет (см. АРХИТЕКТУРА-PWA.md, раздел 3.3).
 */

import type { IdeaStatus } from '../data'

/** Поля документа, по которым ищет индекс. */
export type SearchField = 'title' | 'body' | 'materials'

/** Порядок объединения слов запроса. */
export type SearchCombine = 'AND' | 'OR' | 'AND_NOT'

/** Функция, решающая для конкретного слова, искать ли его по началу. */
export type SearchPrefixRule = (term: string, index: number, terms: string[]) => boolean

/** Функция, решающая для конкретного слова, сколько опечаток прощать. */
export type SearchFuzzyRule = (
  term: string,
  index: number,
  terms: string[],
) => boolean | number

/** Одна находка поиска. */
export interface SearchHit {
  /** `id` идеи — по нему экран читает запись целиком. */
  id: string
  /** Заголовок из индекса: показать результат можно, не трогая базу. */
  title: string
  status: IdeaStatus
  /** Чем больше, тем релевантнее. Порядок результатов — по убыванию. */
  score: number
  /** Слова документа, которые совпали (пригодится для подсветки). */
  terms: string[]
  /** В каких полях нашлось совпадение. */
  fields: SearchField[]
}

/**
 * Настройки одного запроса.
 * Всё необязательное: разумные значения по умолчанию заданы в сервисе.
 */
export interface SearchQueryOptions {
  /** Сколько результатов вернуть. По умолчанию 20; `0` — без ограничения. */
  limit?: number
  /** Искать по началу слова (по умолчанию — да, для слов от двух букв). */
  prefix?: boolean | SearchPrefixRule
  /** Сколько опечаток прощать (по умолчанию — одну, словам от четырёх букв). */
  fuzzy?: boolean | number | SearchFuzzyRule
  /** Требовать все слова (`AND`) или хватит одного (`OR`). */
  combineWith?: SearchCombine
}

/** Состояние индекса — для отладки и проверок. */
export interface SearchStats {
  /**
   * Откуда взялся индекс в памяти:
   * `saved` — прочитан из IndexedDB, `rebuilt` — собран заново,
   * `empty` — ещё не готов.
   */
  source: 'empty' | 'saved' | 'rebuilt'
  /** Сколько идей в индексе; удалённые сюда не попадают. */
  ideas: number
  /** Сколько слов в индексе. */
  terms: number
  /** Размер сохранённого индекса в байтах. */
  bytes: number
  /** Когда индекс последний раз сохраняли; `null` — ещё ни разу. */
  saved_at: string | null
}
