/**
 * Типы расшифровки речи.
 *
 * Задача сервиса узкая: получить байты видео или голосовой заметки и вернуть
 * текст, длительность и стоимость. Ни базы, ни интерфейса, ни очереди здесь
 * нет — решение «что делать с транскриптом» принимает вызывающий код
 * (СХЕМА-ДАННЫХ.md: поле `transcript` у материала).
 *
 * Типы намеренно не знают ни про ffmpeg, ни про конкретного провайдера:
 * сегодня это polza.ai, завтра — любой OpenAI-совместимый сервис, и
 * меняется только реализация, а не интерфейс.
 */

/** Этап задания: по ним интерфейс рисует, что именно происходит. */
export type TranscriptionStage =
  /** Осмотр файла и решение «влезает или вырезаем звук». */
  | 'check'
  /** Вырезание звуковой дорожки из видео (ffmpeg). */
  | 'extract'
  /** Отправка файла провайдеру. */
  | 'upload'
  /** Ожидание ответа распознавания. */
  | 'wait'
  /** Разбор ответа и подсчёт стоимости. */
  | 'finish'

/** Событие прогресса: 0..1 по всему заданию, чтобы рисовать полосу. */
export interface TranscriptionProgress {
  /** Общий прогресс задания: 0 в начале, 1 в конце. Не убывает. */
  progress: number
  stage: TranscriptionStage
  /** Прогресс внутри этапа, 0..1; `null` — этап неделим. */
  stageProgress: number | null
  /** Готовая фраза для интерфейса. */
  message: string
}

/**
 * Что расшифровываем. Оригинал не изменяется и никуда не записывается:
 * сервис только читает байты.
 */
export interface TranscriptionSource {
  blob: Blob
  /** Тип содержимого (`video/mp4`, `audio/mpeg`, …). */
  mimeType?: string | null
  /** Имя файла: нужно для расширения во временном имени ffmpeg. */
  name?: string | null
  /**
   * Длительность, если вызывающий код её уже знает (например, из метаданных
   * видео). Самый приоритетный источник: если она передана, сервис не читает
   * файл заново. Если нет — длительность читается из файла, затем берётся
   * `encodedSec` вырезания. Ответ `json` поля `duration` не гарантирует,
   * и требовать его нельзя; если провайдер всё же пришлёт длительность,
   * она уточнит нашу.
   */
  durationSec?: number | null
}

/** Задание на расшифровку. */
export interface TranscriptionJob {
  source: TranscriptionSource
  /** Прогресс 0..1 — длинная загрузка должна быть видна. */
  onProgress?: (event: TranscriptionProgress) => void
  /** Отмена: закрыл карточку — загрузка и вырезание прекращаются. */
  signal?: AbortSignal
}

/** Звук, вырезанный из видео: то, что реально уходит провайдеру. */
export interface TranscriptionAudio {
  blob: Blob
  mimeType: string
  /** Длительность вырезанного звука, если ffmpeg её назвал (это наш `encodedSec`). */
  durationSec: number | null
}

/**
 * Что решили о языке записи.
 *
 * `unknown` — букв в тексте слишком мало, чтобы судить (короткая реплика,
 * одни цифры): тогда лишний запрос не делается, и запись считается русской.
 */
export type TranscriptionLanguage = 'ru' | 'other' | 'unknown'

/**
 * Почему понадобилась запасная модель.
 *
 * `language` — речь не на русском, и текст перезапросили общей моделью;
 * `provider` — основная модель не ответила по временной причине, и её
 * подменила запасная. Различать важно: во втором случае запись может быть
 * русской, и говорить человеку «речь не на русском» нельзя.
 */
export type TranscriptionFallbackReason = 'language' | 'provider'

/**
 * Успех: ровно то, что нужно положить в материал.
 *
 * `durationSec` — длительность отправленного звука из своих данных: явно
 * переданная, прочитанная из файла или из вырезания; `null` — не знали её
 * и провайдер тоже не назвал. `costRub` — стоимость **успешных** попыток
 * (за нерусскую речь их две и заплачено за обе; после сбоя основной —
 * только за ту, что действительно ответила). Неизвестная длительность даёт
 * `costRub: null`, а не 0: ноль означал бы «бесплатно», хотя запрос уже
 * потратил деньги. Вызывающий код обязан показать неизвестность честно.
 */
export interface TranscriptionResult {
  text: string
  /** Длительность отправленного звука, с; `null` — определить не удалось. */
  durationSec: number | null
  /** Стоимость успешных попыток по минутным тарифам, ₽; `null` — неизвестна. */
  costRub: number | null
  /** Модель, чей текст взят в итоге (идентификатор у провайдера). */
  model: string
  /** Что решили о языке записи по тексту, который взят в итоге. */
  language: TranscriptionLanguage
  /** Была ли вторая попытка запасной моделью: за неё заплачено. */
  usedFallback: boolean
  /** Почему сработала запасная модель; `null` — не срабатывала. */
  fallbackReason: TranscriptionFallbackReason | null
  /**
   * Что стоит сказать человеку дополнительно. `null` — говорить нечего.
   *
   * Появилось из-за денег: если запись не на русском, а запасная модель
   * **не ответила**, мы возвращаем текст основной модели, а не ошибку.
   * Иначе выходит, что человек заплатил за расшифровку и не получил ничего —
   * хотя текст (пусть и хуже) у нас уже на руках.
   *
   * Второй случай — сбой основной модели: примечание объясняет, почему
   * сработала запасная и что списано только за удачную попытку.
   */
  note: string | null
}

/**
 * Коды ошибок. По коду вызывающий код решает, ставить ли задачу на повтор
 * и что показать человеку.
 */
export type TranscriptionErrorCode =
  /** Ключ не задан — запрос в сеть не уходит вообще. */
  | 'no_key'
  /** Пустой файл: расшифровывать нечего. */
  | 'invalid_file'
  /** Среда не подходит (нет fetch) или модель не умеет то, что мы просим. */
  | 'unsupported'
  /** Сеть недоступна, соединение оборвалось. */
  | 'network'
  /** Провайдер не ответил за отведённое время. */
  | 'timeout'
  /** Отменено вызывающим кодом. */
  | 'aborted'
  /** 401/403: ключ отклонён или у него нет прав. */
  | 'auth'
  /** 402: не хватает средств на счёте. */
  | 'budget'
  /** 413 или файл больше лимита даже после вырезания звука. */
  | 'too_large'
  /** 429: слишком много запросов. */
  | 'rate_limit'
  /** 5xx: сервис распознавания недоступен. */
  | 'server'
  /** Прочий отказ провайдера (4xx). */
  | 'http'
  /** Ответ не является JSON. */
  | 'invalid_json'
  /** Ответ без текста: обрезанный ответ или асинхронная модель. */
  | 'empty_response'
  /**
   * В записи нет речи. Это **не поломка**: ролики без слов — обычное дело,
   * поэтому интерфейс показывает такой результат спокойно, без красного.
   */
  | 'no_speech'
  /**
   * Звук не удалось вырезать (ffmpeg не справился). В сообщении — понятная
   * причина и последние осмысленные строки лога ffmpeg, а не только код выхода.
   */
  | 'extract_failed'

/**
 * Понятная ошибка вместо «что-то пошло не так».
 * Сервис не бросает её наружу: она приходит в результате (`ok: false`),
 * поэтому исходный материал остаётся у вызывающего кода.
 */
export class TranscriptionError extends Error {
  readonly code: TranscriptionErrorCode
  /** Стоит ли пробовать снова (например, появилась сеть). */
  readonly retriable: boolean
  /** HTTP-код, если ошибка пришла от провайдера. */
  readonly status: number | null
  /**
   * Пояснение провайдера, если оно было: только его причина, без наших
   * советов и без вычищенных фраз вроде «выберите другую модель».
   * Нужно, чтобы показать причины обеих моделей, не повторяя общие слова.
   */
  readonly detail: string | null

  constructor(
    code: TranscriptionErrorCode,
    message: string,
    options: { retriable?: boolean; status?: number | null; detail?: string | null; cause?: unknown } = {},
  ) {
    super(message, options.cause !== undefined ? { cause: options.cause } : undefined)
    this.name = 'TranscriptionError'
    this.code = code
    this.retriable = options.retriable ?? false
    this.status = options.status ?? null
    this.detail = options.detail ?? null
  }
}

/** Итог расшифровки: либо текст со стоимостью, либо понятная причина отказа. */
export type TranscriptionOutcome =
  | { ok: true; result: TranscriptionResult }
  | { ok: false; error: TranscriptionError }
