/**
 * Живой ли файл в хранилище.
 *
 * НАСТОЯЩАЯ ПРОБЛЕМА, найденная на телефоне автора: в базе остаётся запись
 * «видео, 231 МБ», а СОДЕРЖИМОГО НЕТ. Проявляется так: плеер чёрный,
 * расшифровка говорит «в записи нет речи», ffmpeg отвечает
 * `NotFoundError: The object can not be found here`, кадры не берутся.
 * При этом размер в списке показывается — потому что он записан отдельно.
 *
 * Причина: браузер **молча вытесняет** данные, когда ему мало места.
 * Особенно большие видео. Молча — это и есть худшее: человек уверен, что
 * файл у него, а файла нет.
 *
 * Что делаем: **проверяем чтением**. Дешёвая проверка — прочитать один
 * байт. Если хранилище отдало данные, файл живой; если бросило — он
 * потерян, и об этом надо сказать ЧЕСТНО, а не показывать битый плеер.
 */

/**
 * Читается ли файл на самом деле.
 *
 * Читаем **один байт**, а не весь файл: для 231 МБ полное чтение было бы
 * издевательством. Одного байта достаточно — он лежит в том же хранилище,
 * что и остальное, и если данные вытеснены, отказ придёт сразу.
 */
export async function isReadable(blob: Blob | null | undefined, timeoutMs = 4000): Promise<boolean> {
  if (!blob) return false
  // Пустой блоб — не файл.
  if (blob.size <= 0) return false
  try {
    const result = await withTimeout(blob.slice(0, 1).arrayBuffer(), timeoutMs)
    return result.byteLength > 0
  } catch {
    // `NotFoundError`, `NotReadableError` и прочее — всё означает одно:
    // данных нет. Разбираться в оттенках отказа человеку незачем.
    return false
  }
}

/** Обещание с ограничением по времени: зависшее чтение тоже отказ. */
function withTimeout<T>(promise: Promise<T>, ms: number): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('время вышло')), ms)
    promise.then(
      (value) => {
        clearTimeout(timer)
        resolve(value)
      },
      (error) => {
        clearTimeout(timer)
        reject(error)
      },
    )
  })
}

