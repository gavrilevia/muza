/**
 * Промпт «понять картинку».
 *
 * Один ответ решает две задачи сразу, и это осознанно:
 * - ТЕКСТ с изображения нужен поиску — без него скриншот чека или рецепта
 *   не находится ни по одному слову;
 * - КОРОТКОЕ ОПИСАНИЕ нужно разбору направлений — по одному имени файла
 *   `IMG_3512.png` модель не поймёт, что это «подарок» или «кухня».
 *
 * Разделять это на два платных запроса незачем: модель уже смотрит на
 * картинку, и второй проход стоил бы ещё раз.
 */

import type { LlmContentPart, LlmMessage } from '../ai'
import type { PreparedImage } from './types'

/** Инструкция. Формат — обычный текст: JSON здесь ни к чему, это не разбор схемы. */
export const IMAGE_UNDERSTANDING_PROMPT = `Посмотри на изображение и сделай две вещи в одном ответе.

1. Прочитай ВЕСЬ видимый текст — дословно, на языке оригинала, без перевода и исправлений. Сохрани порядок строк, заголовки, списки, цены и подписи. Если текст мелкий или частично перекрыт, прочитай то, что различимо.
2. Коротко, в 2–4 предложениях, опиши, что изображено и о чём это: предмет, место, блюдо, товар, ситуация. Пиши простыми словами, как для себя.

Формат ответа — обычный текст, без markdown и без JSON:
Текст с картинки:
<прочитанный текст или «нет»>

Описание:
<короткое описание>

Если текста на изображении нет, так и напиши: «Текст с картинки: нет». Всё равно опиши изображение. Не придумывай того, чего не видно, и не давай советов.`

/**
 * Сообщение для модели: одна текстовая часть и одна картинка.
 *
 * Составной `content` здесь обязателен: строкой изображение не передать.
 * У всех остальных сообщений в приложении `content` остаётся строкой, и их
 * тело запроса не меняется.
 */
/**
 * Промпт для КАДРОВ видео.
 *
 * Отличается от картинки по смыслу задачи: один снимок — это «что здесь»,
 * а ряд кадров — это «что происходит в ролике». Поэтому просим не перечень,
 * а суть: о чём запись и что в ней показывают.
 *
 * Честно про предел: если в ролике ГОВОРЯТ, кадры речи не заменят. Они
 * нужны для записей без слов — там, где расшифровывать нечего.
 */
export const FRAMES_UNDERSTANDING_PROMPT = `Это несколько кадров из одного видео, по порядку.

Расскажи, что в этом ролике:
1. Что показывают: предмет, место, действие, люди.
2. Прочитай ВЕСЬ видимый текст на кадрах — дословно, как есть.
3. Если понятно, о чём запись, — скажи одной фразой.

Пиши коротко и по делу. Если по кадрам ничего понять нельзя, так и скажи.

ВЕРНИ ТЕКСТ В ТАКОМ ВИДЕ:
Что показывают: одна-две фразы.
Текст на кадрах: что видно, или «текста нет».`

/** Сообщение с НЕСКОЛЬКИМИ кадрами: модель читает их как один ролик. */
export function buildFramesMessages(frames: readonly string[]): LlmMessage[] {
  const content: LlmContentPart[] = [
    { type: 'text', text: FRAMES_UNDERSTANDING_PROMPT },
    ...frames.map((url) => ({ type: 'image_url' as const, image_url: { url } })),
  ]
  return [{ role: 'user', content }]
}

export function buildImageUnderstandingMessages(prepared: PreparedImage): LlmMessage[] {
  const content: LlmContentPart[] = [
    { type: 'text', text: IMAGE_UNDERSTANDING_PROMPT },
    { type: 'image_url', image_url: { url: prepared.dataUrl } },
  ]
  return [{ role: 'user', content }]
}
