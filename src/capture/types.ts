/**
 * Типы модуля захвата.
 *
 * Захват — это «принять мысль за 1–2 действия и сразу сохранить».
 * Никакой обработки, никакой сети: всё, что здесь описано, живёт в браузере
 * и в IndexedDB (см. АРХИТЕКТУРА-PWA.md, раздел 4).
 *
 * Файл содержит только типы: логика решений — в `logic.ts`, запись — в
 * `materials.ts` и `captureService.ts`.
 */

import type { Idea, Material } from '../data'

/**
 * Канал захвата — откуда пришла идея.
 *
 * Это внутреннее имя канала, а не значение `captured_via`: одному каналу
 * может соответствовать несколько значений схемы (например, файл из
 * галереи — `gallery_import`, а файл из файлового менеджера — `files_save`).
 * Перевод канала в `captured_via` делает `capturedViaFor`.
 */
export type CaptureChannel = 'text' | 'share' | 'file' | 'camera' | 'voice' | 'clipboard'

/** Минимум, который нужен от файла, чтобы принять решение о материале. */
export interface FileLike {
  name: string
  type: string
  size: number
}

/**
 * Файл, готовый к сохранению.
 *
 * Blob отдельно от `File`: делиться из другого приложения и из буфера обмена
 * приходит именно Blob, а конструктор `File` есть не во всех браузерах
 * (Safari долго его не поддерживал). Здесь достаточно Blob плюс имя и тип.
 */
export interface CaptureFile extends FileLike {
  blob: Blob
}

/** Заготовка материала: файл, готовый текст или ссылка. */
export type CaptureMaterialDraft =
  | { kind: 'file'; file: CaptureFile; durationSec?: number | null }
  | { kind: 'text'; text: string; title?: string | null }
  | { kind: 'link'; url: string; title?: string | null }

/**
 * Запрос на захват идеи. Всё необязательное, кроме канала: пустая идея
 * без текста и без файлов не создаётся — это проверяет вызывающий код.
 */
export interface CaptureRequest {
  channel: CaptureChannel
  /** Текст идеи: из поля ввода, из буфера или от источника «Поделиться». */
  text?: string | null
  /** Заголовок от источника («Поделиться» присылает заголовок страницы). */
  sourceTitle?: string | null
  /** Ссылка от источника. */
  url?: string | null
  /** Файлы: снимок, файл, картинка из буфера, запись голоса. */
  files?: readonly CaptureFile[]
  /** Длительность записи голоса в секундах — для подписи и поля материала. */
  durationSec?: number | null
}

/**
 * Материал вместе с самим файлом.
 *
 * Отдельного хранилища для содержимого файлов в схеме нет, поэтому байты
 * лежат в поле `blob` той же записи: IndexedDB кладёт Blob как есть, ничего
 * не кодируя, и файл не теряется при перезагрузке. Поле объявлено в типе
 * `Material` (см. `src/data/types.ts`), а этот псевдоним остался для кода
 * захвата: ему важно, что у материала есть содержимое.
 */
export type StoredMaterial = Material

/** Что получилось в итоге захвата. */
export interface CaptureOutcome {
  /** Идея уже в базе: сбой материалов её не отменяет. */
  idea: Idea
  materials: StoredMaterial[]
  /**
   * Предупреждение, при котором идея сохранена, а часть материалов — нет.
   * `null` — всё в порядке.
   */
  warning: string | null
}

/**
 * Что получилось из запроса целиком.
 *
 * Файлов несколько — идей тоже несколько: по одной на файл. Поэтому итог —
 * список исходов, а не один. Сбой на одном файле не отменяет остальные,
 * поэтому рядом лежит счётчик неудач и готовое объяснение для человека.
 */
export interface CaptureBatchOutcome {
  /** Сохранённые идеи в порядке файлов: первая идея — первый файл. */
  outcomes: CaptureOutcome[]
  /** Сколько файлов сохранить не удалось; `0` — сохранились все. */
  failed: number
  /** Что сказать человеку, если прошло не всё; `null` — всё в порядке. */
  warning: string | null
  /** Текст человека ушёл в идею — поле ввода можно очищать. */
  textConsumed: boolean
}
